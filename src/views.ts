import { randomBytes } from 'node:crypto';
import * as vscode from 'vscode';
import type { DisplayStep } from './walkthrough';

export const VIEW_IDS = {
  outline: 'explorer.questionOutline',
  explanation: 'explorer.explanation',
};

type ViewKind = keyof typeof VIEW_IDS;

export type ViewAction =
  | { type: 'ready' | 'demo' | 'ask' }
  | { type: 'jump'; id: string }
  | { type: 'followup'; id: string; question: string };

export interface ViewState {
  question?: string;
  overview?: string;
  demo: boolean;
  demoFollowup: string;
  steps: DisplayStep[];
  activeId?: string;
  busy: string;
  notice: string;
}

/** Resolve an asset URL that the webview sandbox can read. */
function assetUrl(webview: vscode.Webview, media: vscode.Uri, file: string): vscode.Uri {
  return webview.asWebviewUri(vscode.Uri.joinPath(media, file));
}

/** Build the HTML shell and restrict it to the packaged CSS and nonce-bearing script. */
function viewHtml(webview: vscode.Webview, media: vscode.Uri, kind: ViewKind): string {
  const nonce = randomBytes(16).toString('hex');
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src ${webview.cspSource}; script-src 'nonce-${nonce}'">
  <link rel="stylesheet" href="${assetUrl(webview, media, 'view.css')}">
  <title>Explorer</title>
</head>
<body data-kind="${kind}">
  <main id="content"></main>
  <footer id="actions"></footer>
  <script nonce="${nonce}" src="${assetUrl(webview, media, 'view.js')}"></script>
</body>
</html>`;
}

/** Accept only recognized messages with the required fields for the originating view. */
function readAction(kind: ViewKind, value: unknown): ViewAction | undefined {
  if (!value || typeof value !== 'object') {
    return;
  }
  const { type, id, question } = value as Record<string, unknown>;
  if (type === 'ready' || type === 'demo' || type === 'ask') {
    return { type };
  }
  if (type === 'jump' && kind === 'outline' && typeof id === 'string') {
    return { type, id };
  }
  if (type === 'followup' && kind === 'explanation' && typeof id === 'string' && typeof question === 'string') {
    return { type, id, question };
  }
}

export class WalkthroughViews {
  private readonly openViews = new Map<ViewKind, vscode.WebviewView>();
  private readonly media: vscode.Uri;

  /** Locate the frontend assets relative to the installed extension. */
  constructor(extensionUri: vscode.Uri) {
    this.media = vscode.Uri.joinPath(extensionUri, 'media');
  }

  /** Attach a VS Code view and forward valid frontend actions to the controller. */
  attach(kind: ViewKind, view: vscode.WebviewView, onAction: (action: ViewAction) => void): void {
    const webview = view.webview;
    webview.options = { enableScripts: true, localResourceRoots: [this.media] };
    this.openViews.set(kind, view);

    const messages = webview.onDidReceiveMessage(value => {
      const action = readAction(kind, value);
      if (action) {
        onAction(action);
      }
    });
    const disposal = view.onDidDispose(() => {
      if (this.openViews.get(kind) === view) {
        this.openViews.delete(kind);
      }
      messages.dispose();
      disposal.dispose();
    });
    webview.html = viewHtml(webview, this.media, kind);
  }

  /** Send the same walkthrough state to both open views. */
  publish(state: ViewState): void {
    for (const view of this.openViews.values()) {
      void view.webview.postMessage({ type: 'state', ...state });
    }
  }

  /** Open and focus a view using the command generated by VS Code for its ID. */
  async focus(kind: ViewKind): Promise<void> {
    await vscode.commands.executeCommand(VIEW_IDS[kind] + '.focus');
  }
}
